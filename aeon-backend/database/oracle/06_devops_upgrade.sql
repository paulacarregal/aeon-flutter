-- Incremental and idempotent upgrade used by the CI/CD pipeline.
-- The base schema (01_schema.sql) must already exist in the target database.

DECLARE
    v_base_tables NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_base_tables
    FROM user_tables
    WHERE table_name IN ('USUARIO', 'LOCAL', 'AVALIACAO');

    IF v_base_tables < 3 THEN
        RAISE_APPLICATION_ERROR(
            -20100,
            'Schema base ausente. Execute 01_schema.sql e 02_seed.sql antes do upgrade.'
        );
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM user_tables
    WHERE table_name = 'LOCAL_IMPULSIONAMENTO';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'~
            CREATE TABLE local_impulsionamento (
                id_impulsionamento NUMBER GENERATED BY DEFAULT AS IDENTITY,
                id_local NUMBER NOT NULL,
                data_inicio DATE NOT NULL,
                data_fim DATE NOT NULL,
                peso_bonus NUMBER(5, 2) DEFAULT 0 NOT NULL,
                status VARCHAR2(20) DEFAULT 'ATIVO' NOT NULL,
                objetivo VARCHAR2(300),
                data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT pk_local_impulsionamento
                    PRIMARY KEY (id_impulsionamento),
                CONSTRAINT fk_impulsionamento_local FOREIGN KEY (id_local)
                    REFERENCES local (id_local),
                CONSTRAINT ck_impulsionamento_status CHECK (
                    status IN ('ATIVO', 'PAUSADO', 'ENCERRADO')
                ),
                CONSTRAINT ck_impulsionamento_peso CHECK (
                    peso_bonus BETWEEN 0 AND 20
                ),
                CONSTRAINT ck_impulsionamento_periodo CHECK (
                    data_fim >= data_inicio
                )
            )
        ~';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM user_tables
    WHERE table_name = 'AUDITORIA_IMPULSIONAMENTO';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'~
            CREATE TABLE auditoria_impulsionamento (
                id_auditoria NUMBER GENERATED BY DEFAULT AS IDENTITY,
                id_impulsionamento NUMBER NOT NULL,
                id_local NUMBER NOT NULL,
                acao VARCHAR2(20) NOT NULL,
                status_anterior VARCHAR2(20),
                status_novo VARCHAR2(20),
                peso_anterior NUMBER(5, 2),
                peso_novo NUMBER(5, 2),
                data_evento TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT pk_auditoria_impulsionamento
                    PRIMARY KEY (id_auditoria),
                CONSTRAINT fk_aud_impulsionamento
                    FOREIGN KEY (id_impulsionamento)
                    REFERENCES local_impulsionamento (id_impulsionamento),
                CONSTRAINT fk_aud_impulsionamento_local
                    FOREIGN KEY (id_local)
                    REFERENCES local (id_local),
                CONSTRAINT ck_aud_impulsionamento_acao CHECK (
                    acao IN ('INSERT', 'UPDATE')
                )
            )
        ~';
    END IF;
END;
