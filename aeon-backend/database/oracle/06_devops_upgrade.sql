DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM user_indexes
    WHERE index_name = 'IX_IMPULSIONAMENTO_LOCAL_STATUS';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE INDEX ix_impulsionamento_local_status
            ON local_impulsionamento (
                id_local,
                status,
                data_inicio,
                data_fim
            )';
    END IF;

    SELECT COUNT(*)
    INTO v_count
    FROM user_indexes
    WHERE index_name = 'IX_AUD_REC_USUARIO_DATA';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE INDEX ix_aud_rec_usuario_data
            ON auditoria_recomendacao (id_usuario, data_evento)';
    END IF;
END;
