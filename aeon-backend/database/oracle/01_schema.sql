CREATE TABLE usuario (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY,
    firebase_uid VARCHAR2(128) NOT NULL,
    nome VARCHAR2(160) NOT NULL,
    perfil VARCHAR2(80) DEFAULT 'USUARIO' NOT NULL,
    data_cadastro TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    prefere_premium CHAR(1) DEFAULT 'N' NOT NULL,
    prefere_novidade CHAR(1) DEFAULT 'N' NOT NULL,
    prefere_ativo CHAR(1) DEFAULT 'N' NOT NULL,
    prefere_diurno CHAR(1) DEFAULT 'N' NOT NULL,
    prefere_social CHAR(1) DEFAULT 'N' NOT NULL,
    prefere_outdoor CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uk_usuario_firebase_uid UNIQUE (firebase_uid),
    CONSTRAINT ck_usuario_prefere_premium CHECK (prefere_premium IN ('S', 'N')),
    CONSTRAINT ck_usuario_prefere_novidade CHECK (prefere_novidade IN ('S', 'N')),
    CONSTRAINT ck_usuario_prefere_ativo CHECK (prefere_ativo IN ('S', 'N')),
    CONSTRAINT ck_usuario_prefere_diurno CHECK (prefere_diurno IN ('S', 'N')),
    CONSTRAINT ck_usuario_prefere_social CHECK (prefere_social IN ('S', 'N')),
    CONSTRAINT ck_usuario_prefere_outdoor CHECK (prefere_outdoor IN ('S', 'N'))
);

CREATE TABLE local (
    id_local NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR2(180) NOT NULL,
    categoria VARCHAR2(80) NOT NULL,
    latitude NUMBER(10, 7) NOT NULL,
    longitude NUMBER(10, 7) NOT NULL,
    endereco VARCHAR2(300),
    nota_media NUMBER(3, 2) DEFAULT 0 NOT NULL,
    ativo CHAR(1) DEFAULT 'S' NOT NULL,
    price_level NUMBER(1) DEFAULT 2 NOT NULL,
    indoor CHAR(1) DEFAULT 'S' NOT NULL,
    daytime CHAR(1) DEFAULT 'S' NOT NULL,
    nightlife CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_local PRIMARY KEY (id_local),
    CONSTRAINT ck_local_nota_media CHECK (nota_media BETWEEN 0 AND 5),
    CONSTRAINT ck_local_ativo CHECK (ativo IN ('S', 'N')),
    CONSTRAINT ck_local_price_level CHECK (price_level BETWEEN 1 AND 4),
    CONSTRAINT ck_local_indoor CHECK (indoor IN ('S', 'N')),
    CONSTRAINT ck_local_daytime CHECK (daytime IN ('S', 'N')),
    CONSTRAINT ck_local_nightlife CHECK (nightlife IN ('S', 'N'))
);

CREATE TABLE tag (
    id_tag NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR2(80) NOT NULL,
    CONSTRAINT pk_tag PRIMARY KEY (id_tag),
    CONSTRAINT uk_tag_nome UNIQUE (nome)
);

CREATE TABLE usuario_tag (
    id_usuario NUMBER NOT NULL,
    id_tag NUMBER NOT NULL,
    CONSTRAINT pk_usuario_tag PRIMARY KEY (id_usuario, id_tag),
    CONSTRAINT fk_usuario_tag_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario),
    CONSTRAINT fk_usuario_tag_tag FOREIGN KEY (id_tag)
        REFERENCES tag (id_tag)
);

CREATE TABLE local_tag (
    id_local NUMBER NOT NULL,
    id_tag NUMBER NOT NULL,
    CONSTRAINT pk_local_tag PRIMARY KEY (id_local, id_tag),
    CONSTRAINT fk_local_tag_local FOREIGN KEY (id_local)
        REFERENCES local (id_local),
    CONSTRAINT fk_local_tag_tag FOREIGN KEY (id_tag)
        REFERENCES tag (id_tag)
);

CREATE TABLE interacao_usuario (
    id_interacao NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario NUMBER NOT NULL,
    id_local NUMBER NOT NULL,
    tipo_interacao VARCHAR2(20) NOT NULL,
    data_interacao TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_interacao_usuario PRIMARY KEY (id_interacao),
    CONSTRAINT fk_interacao_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario),
    CONSTRAINT fk_interacao_local FOREIGN KEY (id_local)
        REFERENCES local (id_local),
    CONSTRAINT ck_interacao_tipo CHECK (
        tipo_interacao IN (
            'VISUALIZOU',
            'CURTIU',
            'SALVOU',
            'VISITOU',
            'IGNOROU'
        )
    )
);

CREATE TABLE avaliacao (
    id_avaliacao NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario NUMBER NOT NULL,
    id_local NUMBER NOT NULL,
    nota NUMBER(2, 1) NOT NULL,
    comentario VARCHAR2(1000),
    data_avaliacao TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_avaliacao PRIMARY KEY (id_avaliacao),
    CONSTRAINT fk_avaliacao_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario),
    CONSTRAINT fk_avaliacao_local FOREIGN KEY (id_local)
        REFERENCES local (id_local),
    CONSTRAINT ck_avaliacao_nota CHECK (nota BETWEEN 0 AND 5)
);

CREATE TABLE historico_recomendacao (
    id_recomendacao NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario NUMBER NOT NULL,
    id_local NUMBER NOT NULL,
    score NUMBER(5, 2) NOT NULL,
    data_recomendacao TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_historico_recomendacao PRIMARY KEY (id_recomendacao),
    CONSTRAINT fk_recomendacao_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario),
    CONSTRAINT fk_recomendacao_local FOREIGN KEY (id_local)
        REFERENCES local (id_local),
    CONSTRAINT ck_recomendacao_score CHECK (score BETWEEN 0 AND 100),
    CONSTRAINT uk_recomendacao_usuario_local UNIQUE (id_usuario, id_local)
);

CREATE TABLE local_impulsionamento (
    id_impulsionamento NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_local NUMBER NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    peso_bonus NUMBER(5, 2) DEFAULT 0 NOT NULL,
    status VARCHAR2(20) DEFAULT 'ATIVO' NOT NULL,
    objetivo VARCHAR2(300),
    data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_local_impulsionamento PRIMARY KEY (id_impulsionamento),
    CONSTRAINT fk_impulsionamento_local FOREIGN KEY (id_local)
        REFERENCES local (id_local),
    CONSTRAINT ck_impulsionamento_status CHECK (
        status IN ('ATIVO', 'PAUSADO', 'ENCERRADO')
    ),
    CONSTRAINT ck_impulsionamento_peso CHECK (peso_bonus BETWEEN 0 AND 20),
    CONSTRAINT ck_impulsionamento_periodo CHECK (data_fim >= data_inicio)
);

CREATE TABLE auditoria_impulsionamento (
    id_auditoria NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_impulsionamento NUMBER NOT NULL,
    id_local NUMBER NOT NULL,
    acao VARCHAR2(20) NOT NULL,
    status_anterior VARCHAR2(20),
    status_novo VARCHAR2(20),
    peso_anterior NUMBER(5, 2),
    peso_novo NUMBER(5, 2),
    data_evento TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_auditoria_impulsionamento PRIMARY KEY (id_auditoria),
    CONSTRAINT fk_aud_impulsionamento FOREIGN KEY (id_impulsionamento)
        REFERENCES local_impulsionamento (id_impulsionamento),
    CONSTRAINT fk_aud_impulsionamento_local FOREIGN KEY (id_local)
        REFERENCES local (id_local),
    CONSTRAINT ck_aud_impulsionamento_acao CHECK (acao IN ('INSERT', 'UPDATE'))
);

CREATE TABLE auditoria_recomendacao (
    id_auditoria NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario NUMBER NOT NULL,
    id_local NUMBER NOT NULL,
    tipo_recomendacao VARCHAR2(40) NOT NULL,
    score_afinidade NUMBER(5, 2) NOT NULL,
    bonus_proximidade NUMBER(5, 2) DEFAULT 0 NOT NULL,
    bonus_impulsionamento NUMBER(5, 2) DEFAULT 0 NOT NULL,
    score_final NUMBER(5, 2) NOT NULL,
    justificativa VARCHAR2(500),
    data_evento TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_auditoria_recomendacao PRIMARY KEY (id_auditoria),
    CONSTRAINT fk_aud_recomendacao_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario),
    CONSTRAINT fk_aud_recomendacao_local FOREIGN KEY (id_local)
        REFERENCES local (id_local),
    CONSTRAINT ck_aud_recomendacao_tipo CHECK (
        tipo_recomendacao IN (
            'PRINCIPAL',
            'COMPLEMENTAR',
            'IMPULSIONADA',
            'COMPLEMENTAR_IMPULSIONADA'
        )
    ),
    CONSTRAINT ck_aud_recomendacao_scores CHECK (
        score_afinidade BETWEEN 0 AND 100
        AND bonus_proximidade BETWEEN 0 AND 20
        AND bonus_impulsionamento BETWEEN 0 AND 20
        AND score_final BETWEEN 0 AND 100
    )
);

CREATE INDEX ix_local_categoria ON local (categoria);
CREATE INDEX ix_usuario_tag_tag ON usuario_tag (id_tag);
CREATE INDEX ix_local_tag_tag ON local_tag (id_tag);
CREATE INDEX ix_interacao_usuario_data ON interacao_usuario (id_usuario, data_interacao);
CREATE INDEX ix_interacao_local_tipo ON interacao_usuario (id_local, tipo_interacao);
CREATE INDEX ix_avaliacao_local ON avaliacao (id_local);
CREATE INDEX ix_recomendacao_usuario_score ON historico_recomendacao (id_usuario, score DESC);
CREATE INDEX ix_impulsionamento_local_status ON local_impulsionamento (id_local, status, data_inicio, data_fim);
CREATE INDEX ix_aud_rec_usuario_data ON auditoria_recomendacao (id_usuario, data_evento);
